-- identity: customers, phone OTP, devices, PIN credentials, sessions, consents (erd §4.1).
-- Descriptions use COMMENT ON so they are stored in the catalog and shown by DB tools.
CREATE SCHEMA IF NOT EXISTS identity;

CREATE TABLE identity.customers (
  id                UUID PRIMARY KEY,
  phone             TEXT NOT NULL UNIQUE CHECK (phone ~ '^\+[1-9][0-9]{6,14}$'),
  phone_verified_at TIMESTAMPTZ NOT NULL,
  onboarding_status TEXT NOT NULL
                    CHECK (onboarding_status IN
                      ('REGISTERED', 'KYC_PENDING', 'KYC_VERIFIED', 'KYC_REJECTED', 'MANUAL_REVIEW')),
  full_name         TEXT NULL,
  date_of_birth     DATE NULL,
  closed_at         TIMESTAMPTZ NULL,
  created_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
  version           INT NOT NULL DEFAULT 0
);

CREATE TRIGGER customers_updated_at BEFORE UPDATE ON identity.customers
  FOR EACH ROW EXECUTE FUNCTION platform.set_updated_at();

COMMENT ON TABLE identity.customers IS 'Wallet customers (erd §4.1)';
COMMENT ON COLUMN identity.customers.id IS 'UUIDv7, generated by the app';
COMMENT ON COLUMN identity.customers.phone IS 'E.164, e.g. +849… (BR-03)';
COMMENT ON COLUMN identity.customers.phone_verified_at IS 'When the phone OTP was verified';
COMMENT ON COLUMN identity.customers.onboarding_status IS 'Onboarding / KYC state (BR-06)';
COMMENT ON COLUMN identity.customers.full_name IS 'From eKYC once verified; display only';
COMMENT ON COLUMN identity.customers.date_of_birth IS 'Used for the age >= 18 check (BR-01)';
COMMENT ON COLUMN identity.customers.closed_at IS 'Set when the customer account is closed';
COMMENT ON COLUMN identity.customers.created_at IS 'Row creation time (UTC)';
COMMENT ON COLUMN identity.customers.updated_at IS 'Last update time, maintained by trigger';
COMMENT ON COLUMN identity.customers.version IS 'Optimistic lock, incremented on each status change';

CREATE TABLE identity.phone_verifications (
  id          UUID PRIMARY KEY,
  phone       TEXT NOT NULL,
  purpose     TEXT NOT NULL CHECK (purpose IN ('REGISTER', 'CHANGE_PHONE', 'NEW_DEVICE')),
  otp_hash    BYTEA NOT NULL,
  attempts    INT NOT NULL DEFAULT 0 CHECK (attempts BETWEEN 0 AND 5),
  expires_at  TIMESTAMPTZ NOT NULL,
  verified_at TIMESTAMPTZ NULL
);

CREATE INDEX phone_verifications_lookup_idx ON identity.phone_verifications (phone, purpose, expires_at);

COMMENT ON TABLE identity.phone_verifications IS 'OTP for registration, phone change and new-device binding';
COMMENT ON COLUMN identity.phone_verifications.id IS 'UUIDv7, generated by the app';
COMMENT ON COLUMN identity.phone_verifications.phone IS 'E.164 phone the OTP was sent to';
COMMENT ON COLUMN identity.phone_verifications.purpose IS 'Why the OTP was issued';
COMMENT ON COLUMN identity.phone_verifications.otp_hash IS 'Hash of the OTP; the plain OTP is never stored';
COMMENT ON COLUMN identity.phone_verifications.attempts IS 'Wrong attempts so far, max 5';
COMMENT ON COLUMN identity.phone_verifications.expires_at IS 'Issued time + 5 minutes';
COMMENT ON COLUMN identity.phone_verifications.verified_at IS 'Set when the OTP was entered correctly';

CREATE TABLE identity.devices (
  id                 UUID PRIMARY KEY,
  customer_id        UUID NOT NULL REFERENCES identity.customers (id),
  device_fingerprint TEXT NOT NULL,
  platform           TEXT NULL,
  model              TEXT NULL,
  app_version        TEXT NULL,
  status             TEXT NOT NULL CHECK (status IN ('ACTIVE', 'REVOKED')),
  bound_at           TIMESTAMPTZ NOT NULL,
  revoked_at         TIMESTAMPTZ NULL
);

CREATE UNIQUE INDEX devices_customer_active_uq ON identity.devices (customer_id) WHERE status = 'ACTIVE';
CREATE INDEX devices_customer_idx ON identity.devices (customer_id);

COMMENT ON TABLE identity.devices IS 'Devices bound to a customer; at most one ACTIVE per customer (BR-38)';
COMMENT ON COLUMN identity.devices.id IS 'Equals the X-Device-Id header';
COMMENT ON COLUMN identity.devices.customer_id IS 'Owner of the device';
COMMENT ON COLUMN identity.devices.device_fingerprint IS 'Generated by the app and kept in secure storage';
COMMENT ON COLUMN identity.devices.platform IS 'OS platform, e.g. ios / android';
COMMENT ON COLUMN identity.devices.model IS 'Device model reported by the app';
COMMENT ON COLUMN identity.devices.app_version IS 'App version at binding time';
COMMENT ON COLUMN identity.devices.status IS 'ACTIVE or REVOKED';
COMMENT ON COLUMN identity.devices.bound_at IS 'Binding time; drives the first-24h limits (BR-38)';
COMMENT ON COLUMN identity.devices.revoked_at IS 'Set when the device is revoked';

CREATE TABLE identity.credentials (
  customer_id      UUID PRIMARY KEY REFERENCES identity.customers (id),
  pin_hash         TEXT NULL,
  pin_failed_count INT NOT NULL DEFAULT 0 CHECK (pin_failed_count >= 0),
  pin_locked_until TIMESTAMPTZ NULL,
  pin_hard_locked  BOOLEAN NOT NULL DEFAULT false,
  pin_updated_at   TIMESTAMPTZ NULL,
  version          INT NOT NULL DEFAULT 0
);

COMMENT ON TABLE identity.credentials IS 'Customer PIN credential (BR-35…40)';
COMMENT ON COLUMN identity.credentials.customer_id IS 'One credential row per customer';
COMMENT ON COLUMN identity.credentials.pin_hash IS 'argon2id PHC string; NULL until the PIN is set';
COMMENT ON COLUMN identity.credentials.pin_failed_count IS 'Consecutive wrong PIN attempts (BR-39)';
COMMENT ON COLUMN identity.credentials.pin_locked_until IS 'Temporary lock end time';
COMMENT ON COLUMN identity.credentials.pin_hard_locked IS 'Hard lock; reset requires OTP + face match';
COMMENT ON COLUMN identity.credentials.pin_updated_at IS 'Last time the PIN was set or changed';
COMMENT ON COLUMN identity.credentials.version IS 'Optimistic lock';

CREATE TABLE identity.refresh_tokens (
  id          UUID PRIMARY KEY,
  customer_id UUID NOT NULL REFERENCES identity.customers (id),
  device_id   UUID NOT NULL REFERENCES identity.devices (id),
  family_id   UUID NOT NULL,
  token_hash  BYTEA NOT NULL UNIQUE,
  replaced_by UUID NULL REFERENCES identity.refresh_tokens (id),
  expires_at  TIMESTAMPTZ NOT NULL,
  revoked_at  TIMESTAMPTZ NULL
);

CREATE INDEX refresh_tokens_family_idx ON identity.refresh_tokens (family_id);
CREATE INDEX refresh_tokens_customer_idx ON identity.refresh_tokens (customer_id);
CREATE INDEX refresh_tokens_device_idx ON identity.refresh_tokens (device_id);

COMMENT ON TABLE identity.refresh_tokens IS 'Rotating refresh tokens';
COMMENT ON COLUMN identity.refresh_tokens.id IS 'UUIDv7, generated by the app';
COMMENT ON COLUMN identity.refresh_tokens.customer_id IS 'Token owner';
COMMENT ON COLUMN identity.refresh_tokens.device_id IS 'Device the token is bound to';
COMMENT ON COLUMN identity.refresh_tokens.family_id IS 'Rotation family; reuse of an old token revokes the whole family';
COMMENT ON COLUMN identity.refresh_tokens.token_hash IS 'SHA-256 of the opaque token';
COMMENT ON COLUMN identity.refresh_tokens.replaced_by IS 'Token issued when this one was rotated';
COMMENT ON COLUMN identity.refresh_tokens.expires_at IS 'Issued time + 30 days';
COMMENT ON COLUMN identity.refresh_tokens.revoked_at IS 'Set when the token is revoked';

CREATE TABLE identity.consents (
  id             UUID PRIMARY KEY,
  customer_id    UUID NOT NULL REFERENCES identity.customers (id),
  consent_type   TEXT NOT NULL
                 CHECK (consent_type IN ('TERMS', 'PERSONAL_DATA', 'BIOMETRIC_DATA', 'DATA_SHARING_BANK')),
  policy_version TEXT NOT NULL,
  granted_at     TIMESTAMPTZ NOT NULL,
  withdrawn_at   TIMESTAMPTZ NULL,
  ip             TEXT NULL,
  user_agent     TEXT NULL
);

CREATE INDEX consents_customer_idx ON identity.consents (customer_id, consent_type);

COMMENT ON TABLE identity.consents IS 'Customer consents (BR-70)';
COMMENT ON COLUMN identity.consents.id IS 'UUIDv7, generated by the app';
COMMENT ON COLUMN identity.consents.customer_id IS 'Customer who gave the consent';
COMMENT ON COLUMN identity.consents.consent_type IS 'Consent kind; biometric consent is recorded separately';
COMMENT ON COLUMN identity.consents.policy_version IS 'Version of the terms that were accepted';
COMMENT ON COLUMN identity.consents.granted_at IS 'When consent was given';
COMMENT ON COLUMN identity.consents.withdrawn_at IS 'When consent was withdrawn';
COMMENT ON COLUMN identity.consents.ip IS 'Client IP, kept as proof of consent';
COMMENT ON COLUMN identity.consents.user_agent IS 'Client user agent, kept as proof of consent';
