-- limits: transaction limit counters and per-payment consumptions (erd §4.5).
-- The schema is named "limits" because LIMIT is an SQL keyword.
-- Descriptions use COMMENT ON so they are stored in the catalog and shown by DB tools.
CREATE SCHEMA IF NOT EXISTS limits;

CREATE TABLE limits.usage (
  customer_id UUID NOT NULL, -- ref identity.customers
  bucket      TEXT NOT NULL
              CHECK (bucket IN ('MONTH_GENERAL', 'MONTH_ESSENTIAL', 'DAY_OWN_ACCOUNT', 'DAY_OTHER')),
  period_key  TEXT NOT NULL,
  used_amount BIGINT NOT NULL DEFAULT 0 CHECK (used_amount >= 0),
  txn_count   INT NOT NULL DEFAULT 0 CHECK (txn_count >= 0),
  version     INT NOT NULL DEFAULT 0,
  updated_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
  PRIMARY KEY (customer_id, bucket, period_key),
  CONSTRAINT usage_period_key_matches_bucket CHECK (
       (bucket LIKE 'MONTH\_%' AND period_key ~ '^[0-9]{4}-[0-9]{2}$')
    OR (bucket LIKE 'DAY\_%'   AND period_key ~ '^[0-9]{4}-[0-9]{2}-[0-9]{2}$'))
);

CREATE TRIGGER usage_updated_at BEFORE UPDATE ON limits.usage
  FOR EACH ROW EXECUTE FUNCTION platform.set_updated_at();

COMMENT ON TABLE limits.usage IS 'Limit counters per customer, bucket and period; locked FOR UPDATE inside the money transaction (BR-29)';
COMMENT ON COLUMN limits.usage.customer_id IS 'Customer the counter belongs to (ref identity.customers, no FK across schemas)';
COMMENT ON COLUMN limits.usage.bucket IS 'MONTH_GENERAL: 100M VND/month limit (BR-25); MONTH_ESSENTIAL: extra allowance for essential services (BR-26); DAY_OWN_ACCOUNT: daily total of top-up/withdraw with own bank account (BR-37); DAY_OTHER: daily total of all other transactions (BR-37)';
COMMENT ON COLUMN limits.usage.period_key IS 'Period in Asia/Ho_Chi_Minh time: YYYY-MM for MONTH_* buckets, YYYY-MM-DD for DAY_* buckets (BR-27)';
COMMENT ON COLUMN limits.usage.used_amount IS 'Amount used in this period, in VND; never negative';
COMMENT ON COLUMN limits.usage.txn_count IS 'Number of transactions counted in this period';
COMMENT ON COLUMN limits.usage.version IS 'Optimistic lock, incremented on each update';
COMMENT ON COLUMN limits.usage.updated_at IS 'Last update time, maintained by trigger';

CREATE TABLE limits.consumptions (
  id          UUID PRIMARY KEY,
  payment_id  UUID NOT NULL, -- ref payment.payments
  customer_id UUID NOT NULL,
  bucket      TEXT NOT NULL,
  period_key  TEXT NOT NULL,
  amount      BIGINT NOT NULL CHECK (amount > 0),
  reverted_at TIMESTAMPTZ NULL,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
  -- A payment consumes each bucket at most once, so retries and reverts are idempotent.
  UNIQUE (payment_id, bucket),
  FOREIGN KEY (customer_id, bucket, period_key)
    REFERENCES limits.usage (customer_id, bucket, period_key)
);

COMMENT ON TABLE limits.consumptions IS 'One row per limit consumption; used to give the limit back idempotently when a payment fails or is reversed';
COMMENT ON COLUMN limits.consumptions.id IS 'UUIDv7, generated by the app';
COMMENT ON COLUMN limits.consumptions.payment_id IS 'Payment that consumed the limit (ref payment.payments, no FK across schemas)';
COMMENT ON COLUMN limits.consumptions.customer_id IS 'Part of the FK to limits.usage';
COMMENT ON COLUMN limits.consumptions.bucket IS 'Part of the FK to limits.usage; unique per payment';
COMMENT ON COLUMN limits.consumptions.period_key IS 'Part of the FK to limits.usage; period the amount was counted in';
COMMENT ON COLUMN limits.consumptions.amount IS 'Amount consumed, in VND; always > 0';
COMMENT ON COLUMN limits.consumptions.reverted_at IS 'Set once when the limit is given back; never set twice (conditional update WHERE reverted_at IS NULL)';
COMMENT ON COLUMN limits.consumptions.created_at IS 'When the limit was consumed';
