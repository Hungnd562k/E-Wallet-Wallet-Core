-- audit: append-only audit trail of security- and money-relevant actions (erd §4.12).
-- Descriptions use COMMENT ON so they are stored in the catalog and shown by DB tools.
create schema if not exists audit;

create table audit.audit_logs
(
    id            uuid primary key,
    occurred_at   timestamptz not null default now(),
    actor_type    text        not null check (actor_type in ('CUSTOMER', 'STAFF', 'MERCHANT', 'SYSTEM')),
    actor_id      uuid        null,
    action        text        not null,
    resource_type text        not null,
    resource_id   text        not null,
    outcome       text        not null check (outcome in ('SUCCESS', 'DENIED', 'ERROR')),
    reason        text        null,
    request_id    text        not null,
    trace_id      text        not null,
    ip            text        null,
    user_agent    text        null,
    metadata      jsonb       not null default '{}' check (jsonb_typeof(metadata) = 'object'),
    constraint audit_logs_staff_reason check (actor_type <> 'STAFF' or reason is not null)
);

create index audit_logs_resource_idx on audit.audit_logs (resource_type, resource_id, occurred_at);
create index audit_logs_actor_idx on audit.audit_logs (actor_id, occurred_at);

-- Append-only (erd §1): rows can be inserted and read, never changed or removed.
create trigger audit_logs_immutable before update or delete on audit.audit_logs
    for each row execute function platform.forbid_mutation();
create trigger audit_logs_no_truncate before truncate on audit.audit_logs
    for each statement execute function platform.forbid_mutation();

comment on table audit.audit_logs is 'Append-only audit trail (BR-64, BR-71); UPDATE/DELETE/TRUNCATE blocked by trigger; kept at least 5 years after the wallet is closed';
comment on column audit.audit_logs.id is 'UUIDv7, generated by the app';
comment on column audit.audit_logs.occurred_at is 'When the action happened (UTC)';
comment on column audit.audit_logs.actor_type is 'Who performed the action: CUSTOMER, STAFF, MERCHANT or SYSTEM';
comment on column audit.audit_logs.actor_id is 'Id of the actor (identity.customers / backoffice.staff_users / merchant.merchants); NULL for SYSTEM or an unauthenticated actor';
comment on column audit.audit_logs.action is 'Dotted action name, e.g. wallet.freeze, kyc.image.view, adjustment.approve';
comment on column audit.audit_logs.resource_type is 'Type of the resource acted on, e.g. wallet, payment, kyc_profile';
comment on column audit.audit_logs.resource_id is 'Id of the resource acted on (public or internal id, as text)';
comment on column audit.audit_logs.outcome is 'SUCCESS, DENIED (authorization refused) or ERROR';
comment on column audit.audit_logs.reason is 'Why the action was taken; required for STAFF actions';
comment on column audit.audit_logs.request_id is 'X-Request-Id of the originating request, for log correlation';
comment on column audit.audit_logs.trace_id is 'W3C trace id (traceparent), for trace correlation';
comment on column audit.audit_logs.ip is 'Client IP address';
comment on column audit.audit_logs.user_agent is 'Client user agent';
comment on column audit.audit_logs.metadata is 'Extra context as a JSON object; must NOT contain CCCD, images, OTP, PIN or tokens (BR-71)';
